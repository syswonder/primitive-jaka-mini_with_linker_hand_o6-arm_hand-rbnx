"""jaka_arm — Robonix arm primitive for the JAKA (jkrc) controller.

Owns `robonix/primitive/arm/*`:

  joint_states  topic_out  ROS 2 /jaka/joint_states (arm joints rad + end effector)
  end_pose      topic_out  ROS 2 /jaka/end_pose      (TCP pose, base frame)
  joint_command topic_in   ROS 2 /jaka/joint_command (position-only write)
  pos_command   topic_in   ROS 2 /jaka/pos_command   (TCP target; IK on provider)

With `end_effector: hand` it additionally owns `robonix/primitive/hand/*`:

  info                     rpc       6 control axes (finger/type per axis)
  move_joint               rpc       set axis positions by name, [0,1]
  state_joint              topic_out ROS 2 /jaka/hand/state_joint (axis [0,1])
  set_joint_speed_limits   rpc       per-axis speed ceilings
  set_joint_torque_limits  rpc       per-axis torque ceilings

These contracts are served on the same provider as the arm contracts: the O6
sits on the controller's RS485 end channel behind one jkrc connection and one
signal table, so it cannot be owned by a separate process.

With the default `end_effector: gripper` the hand contracts stay registered
(the package declares them) but answer ok=false ("hand mode not enabled"):
the same package serves both deployments, so the mode is a config choice,
not a build flavor.

Frame, units and writable-field conventions are documented in CAPABILITY.md.
Motion commands are rejected while `motion_enabled` is false (default) —
a real safety mode, not a fake disable; see config.spec.
"""
from __future__ import annotations

import math
import queue
import threading
import time

from robonix_api import Primitive, Ok, Err
from geometry_msgs.msg import Pose
from sensor_msgs.msg import JointState

from .driver import (
    JakaDriver,
    JOINT_COUNT,
    JOINT_NAMES,
    GRIPPER_JOINT_NAME,
    GRIPPER_STROKE_M,
    HAND_JOINT_NAMES,
)
from .hand import GRASP_ANGLES, OPEN_ANGLES

# One provider serves both families; use their common namespace so
# Atlas does not flag the hand contracts as out-of-namespace.
provider = Primitive(id="jaka_arm", namespace="robonix/primitive")

# codegen products (generated by scripts/build.sh into rbnx-build/codegen/
# proto_gen, auto-added to sys.path by the Primitive constructor).
import hand_pb2  # type: ignore[import-not-found]  # noqa: E402

ALL_JOINT_NAMES = JOINT_NAMES + [GRIPPER_JOINT_NAME]

# ── hand mode (end_effector: hand) ────────────────────────────────────────────
# Control-axis layout of the O6, in firmware order (index 0..5). Must match
# driver.HAND_JOINT_NAMES / HAND_JOINT_UPPER_RAD (asserted below) and the
# deployment URDF. Endpoint semantics follow JointInfo.msg: bend
# 0=extended/1=flexed, oppose 0=neutral/1=full opposition.
_AXES = [
    ("thumb_cmc_pitch",  "thumb",  "bend",   0, "拇指掌指关节屈曲：0=伸直, 1=屈曲"),
    ("thumb_cmc_yaw",    "thumb",  "oppose", 0, "拇指对掌/侧摆：0=中立, 1=完全对掌"),
    ("index_mcp_pitch",  "index",  "bend",   0, "食指掌指关节屈曲：0=伸直, 1=屈曲"),
    ("middle_mcp_pitch", "middle", "bend",   0, "中指掌指关节屈曲：0=伸直, 1=屈曲"),
    ("ring_mcp_pitch",   "ring",   "bend",   0, "无名指掌指关节屈曲：0=伸直, 1=屈曲"),
    ("pinky_mcp_pitch",  "pinky",  "bend",   0, "小指掌指关节屈曲：0=伸直, 1=屈曲"),
]
_HAND_AXIS_NAMES = [a[0] for a in _AXES]
assert _HAND_AXIS_NAMES == HAND_JOINT_NAMES, (
    f"hand axis order drift: {_HAND_AXIS_NAMES} vs {HAND_JOINT_NAMES}")

# ---- module state -----------------------------------------------------------
_driver: JakaDriver | None = None
_cfg: dict = {}
_hand_mode = False
_stop_event = threading.Event()
_state_thread: threading.Thread | None = None
_hand_thread: threading.Thread | None = None
_cmd_queue: "queue.Queue[tuple[str, object] | None]" = queue.Queue()
_cmd_thread: threading.Thread | None = None
_last_motion_warn_s = 0.0
_last_gripper_open_m: float | None = None
_shutdown_done = False
# Last commanded hand axis targets (normalized [0,1], 1=flexed); the
# "unlisted axes hold" rule of move_joint/set_*_limits overlays onto this.
# Seeded from a real read at connect.
# Last commanded hand targets (normalized [0,1], 1 = flexed), or None while
# the pose is unknown. The hand's RS485 reads drop answers that read as 0
# (fully flexed), so an activation-time read cannot be trusted as a target
# seed. Until a full six-axis move_joint (or a gripper_joint open/grip) sets
# all six, partial requests are rejected instead of holding fabricated axes.
_hand_targets: list[float] | None = None


# ---- lifecycle --------------------------------------------------------------
@provider.on_init
def init(cfg: dict):
    global _cfg, _hand_mode
    ip = cfg.get("ip")
    if not ip:
        return Err("config `ip` is required (JAKA controller address)")
    _cfg = dict(cfg)
    end_effector = str(cfg.get("end_effector", "gripper"))
    if end_effector not in ("gripper", "hand"):
        return Err(f"config `end_effector` must be gripper|hand, got {end_effector!r}")
    hand_type = str(cfg.get("hand_type", "right"))
    if hand_type not in ("right", "left"):
        return Err(f"config `hand_type` must be right|left, got {hand_type!r}")
    _hand_mode = end_effector == "hand"

    topics = cfg.get("topics") or {}
    provider.create_publisher(
        contract_id="robonix/primitive/arm/joint_states",
        topic=topics.get("joint_states", "/jaka/joint_states"),
        msg_type=JointState,
        qos="reliable",
    )
    provider.create_publisher(
        contract_id="robonix/primitive/arm/end_pose",
        topic=topics.get("end_pose", "/jaka/end_pose"),
        msg_type=Pose,
        qos="reliable",
    )
    provider.create_subscription(
        contract_id="robonix/primitive/arm/joint_command",
        topic=topics.get("joint_command", "/jaka/joint_command"),
        msg_type=JointState,
        callback=_on_joint_command,
        qos="reliable",
    )
    provider.create_subscription(
        contract_id="robonix/primitive/arm/pos_command",
        topic=topics.get("pos_command", "/jaka/pos_command"),
        msg_type=Pose,
        callback=_on_pos_command,
        qos="reliable",
    )
    if _hand_mode:
        # Axis-level position stream for the dexterous hand, normalized [0,1]
        # (1=flexed) per the hand contracts. The gRPC contracts (info /
        # move_joint / set_joint_*_limits) are registered unconditionally
        # below; only the ROS stream is created in hand mode.
        from hand.msg import JointState as HandJointState

        provider.create_publisher(
            contract_id="robonix/primitive/hand/state_joint",
            topic=topics.get("state_joint", "/jaka/hand/state_joint"),
            msg_type=HandJointState,
            qos="reliable",
        )
    return Ok()


@provider.on_activate
def activate():
    global _driver, _state_thread, _cmd_thread, _hand_thread
    if _driver is None:
        _driver = JakaDriver(
            ip=_cfg["ip"],
            joint_speed_rad_s=float(_cfg.get("joint_speed_rad_s", 1.0)),
            linear_speed_mm_s=float(_cfg.get("linear_speed_mm_s", 100.0)),
            gripper_force=int(_cfg.get("gripper_force", 50)),
            gripper_speed=int(_cfg.get("gripper_speed", 1100)),
            reach_mse_threshold_deg2=float(_cfg.get("reach_mse_threshold_deg2", 1.0)),
            move_timeout_s=float(_cfg.get("move_timeout_s", 10.0)),
            end_effector=str(_cfg.get("end_effector", "gripper")),
            hand_type=str(_cfg.get("hand_type", "right")),
        )
        try:
            _driver.connect()
        except Exception as exc:  # noqa: BLE001
            _driver = None
            return Err(f"connect failed: {exc}")
    if _state_thread is None or not _state_thread.is_alive():
        _stop_event.clear()
        _state_thread = threading.Thread(target=_state_loop, daemon=True)
        _state_thread.start()
    if _cmd_thread is None or not _cmd_thread.is_alive():
        _cmd_thread = threading.Thread(target=_command_worker, daemon=True)
        _cmd_thread.start()
    if _hand_mode and (_hand_thread is None or not _hand_thread.is_alive()):
        _hand_thread = threading.Thread(target=_hand_state_loop, daemon=True)
        _hand_thread.start()
    return Ok()


@provider.on_deactivate
def deactivate():
    """Stop publishing and abort motion; keep the controller connection."""
    _stop_event.set()
    if _state_thread is not None:
        _state_thread.join(timeout=2.0)
    if _hand_thread is not None:
        # A sweep in flight holds a per-finger RC lock for up to ~0.5 s;
        # give the thread a moment rather than tearing the link underneath it.
        _hand_thread.join(timeout=1.0)
    if _driver is not None:
        _driver.stop_motion()
    return Ok()


@provider.on_shutdown
def shutdown():
    """Final cleanup: stop threads, optional homing, power off, logout.

    The framework may invoke this twice on one teardown (Driver CMD_SHUTDOWN,
    then the process-signal fallback); the first call wins.
    """
    global _shutdown_done
    if _shutdown_done:
        return Ok()
    _shutdown_done = True
    _stop_event.set()
    if _cmd_thread is not None:
        # Sentinel before join: the worker blocks on get() until it sees None,
        # so joining first would stall for the full timeout.
        _cmd_queue.put(None)
    for thread in (_state_thread, _hand_thread, _cmd_thread):
        if thread is not None:
            thread.join(timeout=2.0)
    if _driver is not None:
        _home_before_shutdown()
        _driver.disconnect()
    return Ok()


def _home_before_shutdown() -> None:
    """Best-effort end-effector release + move to `shutdown_home_joints`
    before the power-off sequence.

    The end effector opens first so a held object is not dragged by the joint
    move. Deployment opt-in: the key absent = no motion on exit. Respects
    the motion_enabled safety gate; bounded by the driver's move_timeout_s
    and never raises — power-off always proceeds.
    """
    home = _cfg.get("shutdown_home_joints")
    if not home:
        return
    if not bool(_cfg.get("motion_enabled", False)):
        print("[jaka_arm] shutdown: motion_enabled is false; skipping homing",
              flush=True)
        return
    try:
        target = [float(v) for v in home]
    except (TypeError, ValueError):
        print(f"[jaka_arm] shutdown: invalid shutdown_home_joints {home!r}; "
              "skipping homing", flush=True)
        return
    print(f"[jaka_arm] shutdown: opening "
          f"{'hand' if _hand_mode else 'gripper'}, homing to "
          f"{[round(v, 3) for v in target]}", flush=True)
    try:
        # Open first (drops any held object); a failed release is logged but
        # does not block the homing move.
        if not _driver.set_gripper_open_m(GRIPPER_STROKE_M):
            print("[jaka_arm] shutdown: end effector open failed", flush=True)
        if not _driver.move_joints_rad(target):
            print("[jaka_arm] shutdown: homing failed or timed out", flush=True)
    except Exception as exc:  # noqa: BLE001
        print(f"[jaka_arm] shutdown: homing failed: {exc}", flush=True)


# ---- ROS 2 callbacks (executor thread) --------------------------------------
def _on_joint_command(msg: JointState) -> None:
    _cmd_queue.put(("joint", msg))


def _on_pos_command(msg: Pose) -> None:
    _cmd_queue.put(("pose", msg))


# ---- command worker ---------------------------------------------------------
def _command_worker() -> None:
    while True:
        item = _cmd_queue.get()
        if item is None:
            return
        kind, payload = item
        try:
            if kind == "joint":
                _exec_joint_command(payload)
            else:
                _exec_pos_command(payload)
        except Exception as exc:  # noqa: BLE001
            print(f"[jaka_arm] command failed: {exc}", flush=True)


def _motion_denied() -> bool:
    """Motion gate with a rate-limited warning. True = command rejected."""
    if bool(_cfg.get("motion_enabled", False)):
        return False
    global _last_motion_warn_s
    now = time.monotonic()
    if now - _last_motion_warn_s > 10.0:
        _last_motion_warn_s = now
        print("[jaka_arm] motion command rejected: motion_enabled is false",
              flush=True)
    return True


def _exec_joint_command(msg: JointState) -> None:
    global _hand_targets
    if _motion_denied():
        return
    names = list(msg.name)
    positions = list(msg.position)
    if len(names) != len(positions) or not names:
        print(f"[jaka_arm] joint_command: name/position length mismatch "
              f"({len(names)} vs {len(positions)})", flush=True)
        return
    known = set(ALL_JOINT_NAMES) | set(HAND_JOINT_NAMES) if _hand_mode \
        else set(ALL_JOINT_NAMES)
    unknown = set(names) - known
    if unknown:
        print(f"[jaka_arm] joint_command: unknown joints {sorted(unknown)}",
              flush=True)
        return

    arm_names = [n for n in names if n in JOINT_NAMES or n == GRIPPER_JOINT_NAME]
    if arm_names:
        # Fill missing arm joints from current feedback so a subset is allowed.
        current = _driver.get_joint_positions_rad()
        if current is None:
            print("[jaka_arm] joint_command: no current joint feedback", flush=True)
            return
        target = dict(zip(JOINT_NAMES, current, strict=True))
        gripper_open_m = None
        for name, value in zip(names, positions, strict=True):
            if name == GRIPPER_JOINT_NAME:
                gripper_open_m = float(max(0.0, min(float(value), GRIPPER_STROKE_M)))
            elif name in JOINT_NAMES:
                target[name] = float(value)

        if gripper_open_m is not None and _hand_mode:
            if _driver.set_gripper_open_m(gripper_open_m):
                # open/grip is a full six-axis pose: it also (re)seeds the
                # overlay cache, so later partial move_joint requests can hold
                # the other fingers where this pose put them.
                pose = (OPEN_ANGLES
                        if gripper_open_m >= 0.5 * GRIPPER_STROKE_M
                        else GRASP_ANGLES)
                _hand_targets = [1.0 - raw / 255.0 for raw in pose]
        elif gripper_open_m is not None:
            _driver.set_gripper_open_m(gripper_open_m)
        if not _driver.move_joints_rad([target[n] for n in JOINT_NAMES]):
            print("[jaka_arm] joint_command: joint move failed", flush=True)

    if _hand_mode:
        # Hand joints in rad (URDF convention) are commanded only when the
        # message actually lists them. Arm-only or gripper-only messages must
        # not touch the hand: replaying the cached pose would be a no-op at
        # best, and a stale cache right after a grip could re-open a holding
        # hand. Unlisted hand axes within a hand command keep their last
        # target (the overlay rule).
        hand_names = [n for n in names if n in HAND_JOINT_NAMES]
        if hand_names:
            if _hand_targets is None:
                print("[jaka_arm] joint_command: hand pose not yet known; "
                      "command all six hand joints at once (or use the hand "
                      "contracts / gripper_joint) — ignoring the hand part",
                      flush=True)
            else:
                hand_targets = _driver.get_hand_joint_positions_rad()
                if hand_targets is not None:
                    for name, value in zip(names, positions, strict=True):
                        if name in HAND_JOINT_NAMES:
                            hand_targets[HAND_JOINT_NAMES.index(name)] = float(value)
                    if all(v is not None for v in hand_targets):
                        try:
                            if not _driver.set_hand_joint_positions_rad(hand_targets):
                                print("[jaka_arm] joint_command: hand move failed",
                                      flush=True)
                        except ValueError as exc:
                            print(f"[jaka_arm] joint_command: hand target rejected: "
                                  f"{exc}", flush=True)


def _exec_pos_command(msg: Pose) -> None:
    if _motion_denied():
        return
    from scipy.spatial.transform import Rotation as R

    rpy = R.from_quat([msg.orientation.x, msg.orientation.y,
                       msg.orientation.z, msg.orientation.w]).as_euler("xyz")
    if not _driver.move_pose([msg.position.x, msg.position.y, msg.position.z],
                             [float(a) for a in rpy]):
        print("[jaka_arm] pos_command: move failed", flush=True)


# ---- state publisher ---------------------------------------------------------
def _state_loop() -> None:
    hz = float(_cfg.get("state_publish_hz", 50.0))
    period = max(0.01, 1.0 / hz)
    while not _stop_event.wait(period):
        try:
            _publish_state_once()
        except Exception as exc:  # noqa: BLE001
            # A malformed frame must not kill the stream: log and keep the
            # loop alive (the previous code let an exception end the thread,
            # silently stopping all joint_states / end_pose output).
            print(f"[jaka_arm] state publish failed: {exc}", flush=True)


def _publish_state_once() -> None:
    global _last_gripper_open_m
    joints = _driver.get_joint_positions_rad()
    pose = _driver.get_tcp_pose()
    if joints is None:
        return
    state = JointState()
    state.header.frame_id = str(_cfg.get("base_frame", "world"))
    if _hand_mode:
        # Arm joints + hand axes (rad, URDF convention 0=straight) in one
        # message, matching the deployment URDF joint names. Axes with no
        # cached reading (first sweep still pending, or a link-layer failure)
        # are omitted: arm feedback never depends on hand health and no pose
        # is fabricated.
        hand = _driver.get_hand_joint_positions_rad()
        names = list(JOINT_NAMES)
        positions_out = list(joints)
        if hand is not None:
            for name, value in zip(HAND_JOINT_NAMES, hand, strict=True):
                if value is not None:
                    names.append(name)
                    positions_out.append(value)
        state.name = names
        state.position = positions_out
    else:
        gripper = _driver.get_gripper_open_m()
        if gripper is not None:
            _last_gripper_open_m = gripper
        if _last_gripper_open_m is None:
            # No gripper reading yet (first RS485 read still pending, or the
            # channel is down): publish the arm joints alone so arm feedback
            # never depends on gripper health. Once a valid gripper reading
            # arrives the full name set (arm + gripper_joint) resumes on
            # every publish.
            state.name = JOINT_NAMES
            state.position = list(joints)
        else:
            state.name = ALL_JOINT_NAMES
            state.position = list(joints) + [_last_gripper_open_m]
    provider.emit("robonix/primitive/arm/joint_states", state)
    if pose is not None:
        from scipy.spatial.transform import Rotation as R

        pos, rpy = pose
        quat = R.from_euler("xyz", rpy).as_quat()
        end = Pose()
        end.position.x, end.position.y, end.position.z = pos
        end.orientation.x, end.orientation.y = quat[0], quat[1]
        end.orientation.z, end.orientation.w = quat[2], quat[3]
        provider.emit("robonix/primitive/arm/end_pose", end)


# ---- hand state publisher (end_effector: hand) -------------------------------
def _hand_state_loop() -> None:
    """Publish `hand/state_joint` on a best-effort cadence.

    One full sweep costs ~2.3 s (six single-entry RS485 reads, see hand.py),
    so the stream is inherently slow — a sweep per cycle is the floor, and
    between/after sweeps the last cached values are re-emitted so consumers
    see a continuous stream (the contract is driver-native frequency; the
    hand's native read path is this slow). When the link is down the loop
    stops emitting rather than serving a frozen pose as if it were live.
    """
    period = max(0.1, float(_cfg.get("hand_publish_period_s", 0.5)))
    from hand.msg import JointState as HandJointState, JointValue

    while not _stop_event.wait(period):
        if not _driver.refresh_hand_positions():
            continue  # link down: emit nothing instead of a stale pose
        values = _driver.get_hand_joint_positions_normalized()
        if values is None:
            continue
        msg = HandJointState()
        msg.joints = [
            JointValue(name=name, value=float(value))
            for name, value in zip(_HAND_AXIS_NAMES, values, strict=True)
            if value is not None
        ]
        if msg.joints:
            provider.emit("robonix/primitive/hand/state_joint", msg)


# ---- hand gRPC contracts (robonix/primitive/hand/*) --------------------------
def _overlay_hand(items, base=None):
    """Overlay repeated {name, value} onto a copy of `base` (default:
    _hand_targets). Returns (new_vector, None) or (None, error). Rejects —
    never clamps — per the hand contracts: empty request, unknown name,
    duplicate name, non-finite or out-of-[0,1] value. Validation runs before
    the base is resolved, so malformed requests always get their own reason.
    """
    if len(items) == 0:
        return None, "empty request: no axes listed"
    seen = set()
    for it in items:
        name = it.name
        value = it.value
        if name not in _HAND_AXIS_NAMES:
            return None, f"unknown axis name: {name!r} (known: {_HAND_AXIS_NAMES})"
        if name in seen:
            return None, f"duplicate axis name: {name!r}"
        seen.add(name)
        if not math.isfinite(value) or not 0.0 <= value <= 1.0:
            return None, f"value out of range [0,1] for {name!r}: {value}"
    if base is None:
        base = _hand_targets
    if base is None:
        return None, ("hand pose not yet known: send all six axes, or use the "
                      "gripper_joint open/grip command first")
    out = list(base)
    for it in items:
        out[_HAND_AXIS_NAMES.index(it.name)] = float(it.value)
    return out, None


@provider.grpc("robonix/primitive/hand/info")
def hand_info(request, context):
    """Query the hand's control-axis layout (6 axes, self-describing).
    Contract: robonix/primitive/hand/info."""
    _ = request, context
    if not _hand_mode or _driver is None:
        return hand_pb2.GetHandInfo_Response(
            ok=False,
            message="hand mode not enabled (end_effector is not 'hand')"
            if not _hand_mode else "hand not connected")
    joints = [
        hand_pb2.JointInfo(
            finger=finger, type=typ, joint_index=ji, name=name, description=desc
        )
        for (name, finger, typ, ji, desc) in _AXES
    ]
    return hand_pb2.GetHandInfo_Response(ok=True, message="", joints=joints)


@provider.grpc("robonix/primitive/hand/move_joint")
def hand_move_joint(request, context):
    """Set control-axis positions by name (normalized [0,1], 1=flexed). Only
    listed axes move; unlisted hold their last target. Rejects (never clamps)
    empty/unknown/duplicate/out-of-range. ok=true = accepted & dispatched, NOT
    reached. Contract: robonix/primitive/hand/move_joint."""
    _ = context
    global _hand_targets
    if not _hand_mode or _driver is None:
        return hand_pb2.MoveJoint_Response(
            ok=False, message="hand mode not enabled or not connected")
    if _hand_targets is None:
        names = {target.name for target in request.targets}
        if names != set(_HAND_AXIS_NAMES):
            return hand_pb2.MoveJoint_Response(
                ok=False,
                message=("hand pose not yet known: send all six axes, or use "
                         "the gripper_joint open/grip command first"))
        new, err = _overlay_hand(request.targets, base=[0.0] * len(_AXES))
    else:
        new, err = _overlay_hand(request.targets)
    if err:
        return hand_pb2.MoveJoint_Response(ok=False, message=err)
    try:
        ok = _driver.set_hand_joint_positions_normalized(new)
    except Exception as exc:  # noqa: BLE001
        return hand_pb2.MoveJoint_Response(ok=False, message=f"set_joint_pos failed: {exc}")
    if not ok:
        return hand_pb2.MoveJoint_Response(ok=False, message="hand link down")
    _hand_targets = new
    return hand_pb2.MoveJoint_Response(ok=True, message="")


@provider.grpc("robonix/primitive/hand/set_joint_speed_limits")
def hand_set_joint_speed_limits(request, context):
    """Set per-axis speed limits by name (normalized [0,1], 1=fastest). Only
    listed axes updated; values persist across motions in hand mode.
    Contract: robonix/primitive/hand/set_joint_speed_limits."""
    _ = context
    if not _hand_mode or _driver is None:
        return hand_pb2.SetJointSpeedLimits_Response(
            ok=False, message="hand mode not enabled or not connected")
    # Base = the persistent speed limits in effect (driver caches them; the
    # firmware speed registers are rewritten on every motion), so an unlisted
